#!/usr/bin/env bash
set -euo pipefail

# Installs this repository's commands (bin/<name>.mjs) on the PATH as launchers.
# Skills and hooks are not installed here: a repository enables them through
# the marketplace plugins (`harness init`), so nothing of the harness is global.
# Re-runnable. It also removes what earlier versions linked into the Claude Code
# user directory (skills, scripts and hook launchers pointing at this working
# copy), and refuses to touch anything it did not create.

readonly REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
readonly BIN_DIR="${HARNESS_BIN_DIR:-$HOME/.local/bin}"

# Windows refuses symlinks without Developer Mode or elevation, but allows
# directory junctions to any user. Detect once.
readonly IS_WINDOWS=$([[ "$(uname -s)" == MINGW* || "$(uname -s)" == MSYS* ]] && echo 1 || echo 0)

# Identifies a launcher this script generated, so a regenerated one is replaced
# rather than refused, while a stranger's file at the same path is left alone.
readonly LAUNCHER_MARKER='claude-harness:launcher'

make_link() {
  local src="$1" dest="$2"

  # Scripts get a launcher, not a link. A hardlink breaks the moment an editor
  # rewrites the repository copy instead of modifying it in place, and the
  # stale installed copy then runs silently. A launcher cannot go stale.
  if [[ -f "$src" ]]; then
    local target
    if [[ "$IS_WINDOWS" -eq 1 ]]; then target=$(cygpath -w "$src"); else target="$src"; fi
    if [[ "$src" == *.sh ]]; then
      cat > "$dest" <<LAUNCHER
#!/usr/bin/env bash
# $LAUNCHER_MARKER
# Generated by claude-harness/install.sh. Do not edit; edit the repository copy.
exec bash '$src' "\$@"
LAUNCHER
      chmod +x "$dest"
      return
    fi
    cat > "$dest" <<LAUNCHER
#!/usr/bin/env node
// $LAUNCHER_MARKER
// Generated by claude-harness/install.sh. Do not edit; edit the repository copy.
import { spawnSync } from "node:child_process";
const r = spawnSync(process.execPath, [String.raw\`$target\`, ...process.argv.slice(2)], { stdio: "inherit" });
process.exit(r.status ?? 1);
LAUNCHER
    chmod +x "$dest"
    return
  fi

  if [[ "$IS_WINDOWS" -eq 1 ]]; then
    # `cmd //c mklink` mangles paths under Git Bash and fails silently.
    # PowerShell's New-Item takes real Windows paths and works unelevated.
    local win_src win_dest
    win_src=$(cygpath -w "$src")
    win_dest=$(cygpath -w "$dest")
    powershell -NoProfile -NonInteractive -Command \
      "New-Item -ItemType Junction -Path '$win_dest' -Target '$win_src' -ErrorAction Stop | Out-Null" \
      >/dev/null 2>&1
    return
  fi

  ln -s "$src" "$dest"
}

# A junction reports as a directory, not a link, so -L is not enough to tell an
# already-installed entry from a stray copy. Compare identity instead.
already_linked() {
  local src="$1" dest="$2"
  [[ -d "$src" && -d "$dest" ]] && [[ "$dest" -ef "$src" ]] && return 0
  [[ -L "$dest" ]] && [[ "$(readlink "$dest")" == "$src" ]] && return 0
  return 1
}

is_our_launcher() {
  [[ -f "$1" ]] && grep -q "$LAUNCHER_MARKER" "$1" 2>/dev/null
}

link_one() {
  local src="$1" dest="$2" name
  name=$(basename "$dest")

  if already_linked "$src" "$dest"; then
    printf '  ok       %s\n' "$name"
    return 0
  fi

  if [[ -L "$dest" ]] || is_our_launcher "$dest"; then
    rm -f "$dest"
  elif [[ -e "$dest" ]]; then
    # A real file or directory here is either a pre-repo copy or someone
    # else's work. Refuse rather than guess which.
    printf '  REFUSED  %s (exists and is not a link; move it aside first)\n' \
      "$name" >&2
    return 1
  fi

  if ! make_link "$src" "$dest"; then
    printf '  FAILED   %s (could not link)\n' "$name" >&2
    return 1
  fi

  # Verify rather than trust the exit status: mklink has been known to report
  # success on a link that is not there.
  if [[ ! -e "$dest" ]]; then
    printf '  FAILED   %s (link reported success but does not exist)\n' "$name" >&2
    return 1
  fi

  printf '  linked   %s\n' "$name"
}

# Earlier versions linked every skill, script and hook into the user directory,
# which made them global to every repository. Remove only what points here.
unlink_global() {
  local dir="$1" entry removed=0
  [[ -d "$dir" ]] || return 0
  for entry in "$dir"/*; do
    [[ -e "$entry" || -L "$entry" ]] || continue
    if [[ -L "$entry" && "$(readlink "$entry")" == "$REPO_ROOT"/* ]] || is_our_launcher "$entry"; then
      rm -f "$entry"
      printf '  removed  %s\n' "${entry#"$CLAUDE_DIR"/}"
      removed=1
    fi
  done
  return 0
}

main() {
  local failed=0

  printf 'global harness links under %s (removed: repositories enable the plugins)\n' "$CLAUDE_DIR"
  for d in skills scripts hooks; do unlink_global "$CLAUDE_DIR/$d"; done

  # bin/<name>.mjs is a command on the PATH: ~/.local/bin/<name>, a launcher.
  printf 'bin -> %s\n' "$BIN_DIR"
  mkdir -p "$BIN_DIR"
  for cmd in "$REPO_ROOT"/bin/*.mjs; do
    [[ -f "$cmd" && "$cmd" != *.test.mjs ]] || continue
    link_one "$cmd" "$BIN_DIR/$(basename "$cmd" .mjs)" || failed=1
  done

  if [[ "$failed" -ne 0 ]]; then
    printf '\nSome links were refused. Nothing was destroyed.\n' >&2
    return 1
  fi
  printf '\nDone. Next: harness init <repository>, then npm run doctor\n'
}

main "$@"
